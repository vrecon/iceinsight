export function ijsbaanName(locationId?: number | null): string {
  if (locationId === undefined || locationId === null || Number.isNaN(Number(locationId))) {
    return 'Onbekende baan';
  }
  const id = Number(locationId);
  return IJSBANEN[id] ?? 'Onbekende baan';
}

